"""Local synthetic browser acceptance. Start tests/browser-server.ts with with_server.py."""
import json, os, time
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

session = json.loads(Path('.artifacts/browser-session.json').read_text())
with sync_playwright() as p:
    executable = os.getenv('CHROMIUM_PATH')
    browser = p.chromium.launch(headless=True, **({'executable_path': executable} if executable else {}))
    context = browser.new_context(viewport={'width': 1280, 'height': 900})
    context.add_cookies([{'name': 'anymail_session', 'value': session['sid'], 'url': 'http://localhost:4379', 'httpOnly': True, 'sameSite': 'Lax'}])
    page = context.new_page()
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.goto('http://localhost:4379')
    page.wait_for_load_state('networkidle')
    expect(page.get_by_role('heading', name='连接你的邮箱')).to_be_visible()
    page.locator('#accounts').select_option(session['account'])
    expect(page.locator('#accounts')).to_have_value(session['account'])
    print('Rendered headings:', page.get_by_role('heading').all_text_contents())
    page.locator('#search input').fill('发票')
    page.locator('#search button').click()
    page.get_by_role('button', name='测试发票', exact=True).click()
    expect(page.locator('#message')).to_contain_text('Invoice 发票内容')
    page.locator('#draft input[name=to]').fill('synthetic-recipient@example.com')
    page.locator('#draft input[name=bcc]').fill('synthetic-bcc@example.com')
    page.locator('#draft input[name=subject]').fill('浏览器测试草稿')
    page.locator('#draft textarea').fill('这是测试夹具，不会连接真实邮箱。')
    page.locator('#draft input[name=file]').set_input_files({'name':'invoice.txt','mimeType':'text/plain','buffer':b'consented browser attachment'})
    page.locator('#draft button').click()
    expect(page.locator('#approval')).to_be_visible()
    page.screenshot(path='.artifacts/browser-desktop.png', full_page=True)
    page.locator('#approval').click()
    expect(page.get_by_role('heading', name='确认邮件发送')).to_be_visible()
    expect(page.locator('pre')).to_contain_text('synthetic-bcc@example.com')
    expect(page.locator('main')).to_contain_text('test@example.com')
    expect(page.locator('main')).to_contain_text('SHA-256:')
    expect(page.get_by_role('link', name='invoice.txt')).to_be_visible()
    page.get_by_role('button', name='批准这份固定内容的发送').click()
    expect(page.get_by_role('heading', name='已批准')).to_be_visible()
    page.goto('http://localhost:4379')
    page.wait_for_load_state('networkidle')
    page.locator('#accounts').select_option(session['account'])
    pending = []
    def hold(route):
        pending.append(route)
    def held_request():
        deadline = time.monotonic() + 5
        while not pending and time.monotonic() < deadline:
            page.wait_for_timeout(25)
        assert pending, 'Expected delayed request was not intercepted'
        return pending.pop()
    page.route('**/api/call/messages_search', hold)
    page.locator('#search button').click()
    delayed_search = held_request()
    page.locator('#accounts').select_option(session['second'])
    delayed_search.continue_()
    page.wait_for_load_state('networkidle')
    expect(page.locator('#messages')).to_be_empty()
    page.unroute('**/api/call/messages_search', hold)
    page.locator('#accounts').select_option(session['account'])
    page.locator('#drafts').click()
    expect(page.locator('#draft-list button')).to_have_count(1)
    page.route('**/api/call/drafts_prepare_send', hold)
    page.locator('#draft-list button').click()
    delayed_prepare = held_request()
    page.locator('#accounts').select_option(session['second'])
    expect(page.locator('#draft-list')).to_be_empty()
    delayed_prepare.continue_()
    page.wait_for_load_state('networkidle')
    expect(page.locator('#approval')).to_be_hidden()
    expect(page.locator('#draft-result')).to_be_empty()
    page.unroute('**/api/call/drafts_prepare_send', hold)
    page.locator('#push-status').click()
    expect(page.locator('#push-result')).to_contain_text('periodic_reconciliation')
    page.locator('details').first.evaluate('(element)=>element.open=true')
    page.locator('#jmap input[name=email]').fill('test@example.com')
    page.locator('#jmap input[name=sessionUrl]').fill('https://jmap.lab.invalid/session')
    page.locator('#jmap input[name=token]').fill('synthetic-browser-token')
    page.locator('#jmap button').click()
    expect(page.locator('#status')).to_contain_text('JMAP 连接已验证')
    expect(page.locator('#accounts option')).to_have_count(3)
    expect(page.locator('#jmap input[name=token]')).to_have_value('')
    page.set_viewport_size({'width': 390, 'height': 844})
    page.wait_for_load_state('networkidle')
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Mobile horizontal overflow'
    page.screenshot(path='.artifacts/browser-mobile.png', full_page=True)
    page.set_viewport_size({'width': 1280, 'height': 900})
    page.locator('#accounts').select_option(session['account'])
    page.locator('details').evaluate_all('(elements)=>elements.forEach(e=>e.open=true)')
    page.locator('#grant input[name=subject]').fill('browser-member')
    page.locator('#grant input[name=expires]').fill(__import__('datetime').datetime.fromtimestamp(__import__('time').time()+3600).strftime('%Y-%m-%dT%H:%M'))
    page.get_by_role('button', name='授予或更新权限', exact=True).click()
    expect(page.locator('#grant-result')).to_contain_text('browser-member')
    page.locator('#grant-revoke').click()
    expect(page.locator('#grant-result')).to_contain_text('true')
    page.goto('http://localhost:4379/widget-test')
    page.wait_for_load_state('networkidle')
    view=page.frame_locator('#widget')
    expect(view.locator('#accounts option')).to_have_count(3)
    view.locator('#accounts').select_option(session['account'])
    view.locator('#query').fill('发票')
    view.locator('#search button').click()
    view.get_by_role('button', name='测试发票', exact=True).click()
    expect(view.locator('#body')).to_contain_text('Invoice 发票内容')
    view.locator('#to').fill('widget@example.com')
    view.locator('#bcc').fill('widget-bcc@example.com')
    view.locator('#title').fill('MCP Apps 草稿')
    view.locator('#text').fill('Widget synthetic body')
    view.get_by_role('button', name='保存草稿', exact=True).click()
    expect(view.locator('#status')).to_contain_text('草稿已保存')
    view.locator('#prepare').click()
    expect(view.locator('#approval')).to_be_visible()
    view.locator('#approval').click()
    page.wait_for_function('() => window.lastOpened?.includes("/approve/")')
    view.locator('#text').fill('Changed after preparing')
    expect(view.locator('#approval')).to_be_hidden()
    view.locator('#file').click()
    expect(view.locator('#status')).to_contain_text('当前宿主不提供文件库')
    page.set_viewport_size({'width':390,'height':844})
    assert view.locator('html').evaluate('(e)=>e.scrollWidth<=innerWidth'), 'Widget mobile overflow'
    page.screenshot(path='.artifacts/widget-mobile.png', full_page=True)
    assert not errors, errors
    print('PASS: synthetic mail search/read, draft/Bcc preview, sender/attachment-bound approval, stale search/draft account switch, desktop/mobile, no page errors')
    context.close()
    browser.close()
